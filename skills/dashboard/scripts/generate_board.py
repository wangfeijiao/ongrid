REFRESH_CODE = """# Streamlit timed rerun (set every 60s)
import streamlit as st
import pandas as pd
st.set_page_config(layout='wide')
@st.cache_data(ttl=60)
def load(): return pd.read_csv('metrics.csv')
df = load()
st.metric('KPI', df['value'].iloc[-1])
st.line_chart(df)"""

REALTIME_CODE = """// WebSocket + ECharts with reconnect + rate limit
let ws, alive = false;
function connect() {
  ws = new WebSocket('wss://example.org/feed');
  ws.onopen = () => alive = true;
  ws.onclose = () => { alive = false; setTimeout(connect, 2000); };
  ws.onmessage = (e) => { if (alive) chart.setOption(JSON.parse(e.data)); };
}
connect();"""


def load_brief(path):
    return json.load(open(path, encoding="utf-8"))


def rating_of(cfg, sc):
    r = cfg["meta"]["rating"]
    return r["high"] if sc >= 85 else (r["mid"] if sc >= 65 else r["low"])


def build_version(brief, lang, v):
    cfg = LANG[lang]
    refresh = brief.get("refresh", "static")
    sc = score_version(v, BEST_VERSION.get(refresh, "static"))
    return v, sc, rating_of(cfg, sc)


def synthesize(brief, lang):
    cfg = LANG[lang]
    M = cfg["meta"]; L = cfg["labels"]; IN = cfg["inline"]
    metrics = brief.get("metrics", "")
    refresh = brief.get("refresh", "static")
    source = brief.get("source", "")
    rname = REFRESH_NAME.get(refresh, REFRESH_NAME["static"])[lang]
    out = []
    out.append(f"# {M['title']}（{lang}）")
    out.append("")
    out.append(f"> {IN['metrics']}：{metrics} ｜ {IN['refresh']}：{rname} ｜ {IN['source']}：{source} ｜ {IN['language']}：{lang}")
    out.append("")
    out.append(f"## {L['layout']}")
    out.append("")
    out.append("```")
    out.append(LAYOUT)
    out.append("```")
    out.append("")
    results = []
    for v in ["static", "refresh", "realtime"]:
        _, sc, rk = build_version(brief, lang, v)
        results.append((v, sc, rk))
    results.sort(key=lambda x: -x[1])
    best = results[0]
    out.append(f"**{M['total']}（{lang}）：** " + "，".join(
        f"{L['version_names'][r[0]]} {r[1]}{M['pts']}/{r[2]}" for r in results))
    out.append("")
    out.append(f"> {IN['recommended']}：{L['version_names'][best[0]]}（{best[1]}{M['pts']} · {best[2]}）")
    out.append("")
    sep = "：" if lang.startswith("zh") else ": "
    for v, sc, rk in results:
        out.append(f"## {L['version_names'][v]}（{sc}{M['pts']} · {rk}）")
        out.append("")
        for dim, text in DETAIL[lang][v].items():
            out.append(f"- {L['dims'][dim]}{sep} {text}")
        out.append("")
    out.append("## " + M['plan'] + " " + L['recommended'])
    out.append("")
    code = {"static": STATIC_CODE, "refresh": REFRESH_CODE, "realtime": REALTIME_CODE}[best[0]]
    out.append(f"**{L['metrics']} code（{best[0]}）：**")
    out.append("")
    out.append("```")
    out.append(code)
    out.append("```")
    out.append("")
    for t in cfg["tips"]:
        out.append(f"- {t}")
    out.append("")
    out.append(M["credit"])
    out.append(M["footer"])
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--brief", required=True)
    ap.add_argument("--lang", default=None)
    ap.add_argument("--all", action="store_true")
    a = ap.parse_args()
    brief = load_brief(a.brief)
    langs = ["zh-CN", "zh-TW", "en", "ja"] if a.all else [a.lang or brief.get("language", "zh-CN")]
    out = []
    for lg in langs:
        out.append(synthesize(brief, lg))
        out.append("\n\n")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
